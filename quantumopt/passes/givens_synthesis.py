# ── Matrix helpers ────────────────────────────────────────────────────────────

def _u3(theta: float, phi: float, lam: float) -> np.ndarray:
    ct, st = np.cos(theta / 2), np.sin(theta / 2)
    return np.array(
        [[ct, -np.exp(1j * lam) * st],
         [np.exp(1j * phi) * st, np.exp(1j * (phi + lam)) * ct]]
    )


def _embed(U: np.ndarray, qubit: int, n: int = 3) -> np.ndarray:
    dim = 2 ** n
    out = np.eye(dim, dtype=complex)
    for idx in range(dim):
        bits = [(idx >> b) & 1 for b in range(n)]
        for a in range(2):
            nb = bits.copy()
            nb[qubit] = a
            new_idx = sum(b << i for i, b in enumerate(nb))
            out[new_idx, idx] += U[a, bits[qubit]] - (1 if a == bits[qubit] else 0)
    return out


def _cx(ctrl: int, tgt: int, n: int = 3) -> np.ndarray:
    m = np.eye(2 ** n, dtype=complex)
    for idx in range(2 ** n):
        if (idx >> ctrl) & 1:
            ni = idx ^ (1 << tgt)
            m[ni, idx] = 1
            m[idx, idx] = 0
    return m


_CX01 = _cx(0, 1)
_CX12 = _cx(1, 2)
_CX_SEQ = [_CX01, _CX12, _CX01, _CX12, _CX01, _CX12]


def _six_cx_matrix(params: np.ndarray) -> np.ndarray:
    """Evaluate the 6-CX template given 63 U3 parameters (7 layers × 3 qubits × 3)."""
    M = np.eye(8, dtype=complex)
    for layer in range(7):
        for q in range(3):
            off = layer * 9 + q * 3
            M = _embed(_u3(*params[off:off + 3]), q) @ M
        if layer < 6:
            M = _CX_SEQ[layer] @ M
    return M


def _frobenius_dist(U: np.ndarray, V: np.ndarray) -> float:
    best = np.inf
    for k in range(8):
        ph = np.exp(1j * k * np.pi / 4)
        best = min(best, float(np.linalg.norm(U - ph * V, "fro")))
    return best


# ── Target unitary builder ─────────────────────────────────────────────────────

def _naive_xzx_yzy(theta: float) -> np.ndarray:
    """8-CX matrix for exp(-iθ(XZX+YZY)) on 3 qubits."""
    qc = QuantumCircuit(3)
    qc.h(0); qc.h(2)
    qc.cx(0, 1); qc.cx(1, 2); qc.rz(2 * theta, 2); qc.cx(1, 2); qc.cx(0, 1)
    qc.h(0); qc.h(2)
    qc.sdg(0); qc.h(0); qc.sdg(2); qc.h(2)
    qc.cx(0, 1); qc.cx(1, 2); qc.rz(2 * theta, 2); qc.cx(1, 2); qc.cx(0, 1)
    qc.h(0); qc.s(0); qc.h(2); qc.s(2)
    return Operator(qc).data


# ── Optimisation engine ───────────────────────────────────────────────────────

def _optimise_6cx(theta: float, n_trials: int = 50, seed: int = 42) -> np.ndarray:
    """
    Find 63 U3 parameters implementing exp(-iθ(XZX+YZY)) via 6 CX gates.
    Returns the parameter vector; raises RuntimeError if convergence fails.
    """
    U_target = _naive_xzx_yzy(theta)
    rng = np.random.default_rng(seed)

    def cost(p: np.ndarray) -> float:
        return _frobenius_dist(_six_cx_matrix(p), U_target) ** 2

    best_d, best_p = np.inf, None
    for _ in range(n_trials):
        p0 = rng.uniform(-np.pi, np.pi, 63)
        try:
            res = minimize(cost, p0, method="L-BFGS-B",
                           options={"maxiter": 1000, "ftol": 1e-26, "gtol": 1e-10})
            if res.fun < best_d:
                best_d = res.fun
                best_p = res.x
                if best_d < 1e-12:
                    break
        except Exception:
            pass

    if best_p is None or np.sqrt(best_d) > 1e-4:
        raise RuntimeError(
            f"6-CX optimisation failed for θ={theta:.6f} (dist={np.sqrt(best_d):.2e}). "
            "Angle not in precomputed table and on-the-fly search did not converge."
        )
    return best_p


_PARAM_CACHE: Dict[float, np.ndarray] = {}


def _cached_params(theta: float) -> np.ndarray:
    key = round(float(theta), 6)
    if key not in _PARAM_CACHE:
        if key in _PRECOMPUTED_PARAMS:
            _PARAM_CACHE[key] = _PRECOMPUTED_PARAMS[key]
        else:
            _PARAM_CACHE[key] = _optimise_6cx(theta)
    return _PARAM_CACHE[key]


# ── Public circuit builder ────────────────────────────────────────────────────

def givens_hopping_circuit(
    theta: float,
    q_left: int,
    q_jw: int,
    q_right: int,
    n_qubits: int,
) -> QuantumCircuit:
    """
    Return a circuit implementing exp(-iθ(XZX+YZY)) on (q_left, q_jw, q_right)
    using exactly 6 CX gates on the linear chain q_left – q_jw – q_right.
    """
    params = _cached_params(theta)
    qc = QuantumCircuit(n_qubits)
    qs = [q_left, q_jw, q_right]
    cxs = [(q_left, q_jw), (q_jw, q_right),
           (q_left, q_jw), (q_jw, q_right),
           (q_left, q_jw), (q_jw, q_right)]

    for layer in range(7):
        for local_q, global_q in enumerate(qs):
            t, f, l_ = params[layer * 9 + local_q * 3: layer * 9 + local_q * 3 + 3]
            qc.u(t, f, l_, global_q)
        if layer < 6:
            c, tgt = cxs[layer]
            qc.cx(c, tgt)

    return qc


# ── Pattern detection ─────────────────────────────────────────────────────────

def _qubit_idx(inst_qubit, qc: QuantumCircuit) -> int:
    return qc.find_bit(inst_qubit).index


def _match_xzx(instructions: list, start: int, qc: QuantumCircuit) -> Optional[dict]:
    """
    Try to match exp(-iθ XZX) starting at `start`.
    Pattern (9 instructions): h, h, cx, cx, rz, cx, cx, h, h
    """
    if start + 8 >= len(instructions):
        return None
    ops = instructions[start:start + 9]
    names = [op.operation.name for op in ops]
    if names != ["h", "h", "cx", "cx", "rz", "cx", "cx", "h", "h"]:
        return None

    q_left  = _qubit_idx(ops[0].qubits[0], qc)
    q_right = _qubit_idx(ops[1].qubits[0], qc)
    cx1_c   = _qubit_idx(ops[2].qubits[0], qc)
    cx1_t   = _qubit_idx(ops[2].qubits[1], qc)
    cx2_c   = _qubit_idx(ops[3].qubits[0], qc)
    cx2_t   = _qubit_idx(ops[3].qubits[1], qc)
    rz_q    = _qubit_idx(ops[4].qubits[0], qc)
    h3_q    = _qubit_idx(ops[7].qubits[0], qc)
    h4_q    = _qubit_idx(ops[8].qubits[0], qc)

    # Verify structural constraints
    if not (cx1_c == q_left and cx1_t != q_left and cx2_t == q_right):
        return None
    if rz_q != q_right or h3_q != q_left or h4_q != q_right:
        return None

    q_jw = cx1_t
    theta = float(ops[4].operation.params[0]) / 2.0   # keep sign!
    return dict(pauli="XZX", qubits=(q_left, q_jw, q_right),
                theta=theta, end_idx=start + 8)


def _match_yzy(instructions: list, start: int, qc: QuantumCircuit) -> Optional[dict]:
    """
    Try to match exp(-iθ YZY) starting at `start`.
    Pattern (13 instructions): sdg, h, sdg, h, cx, cx, rz, cx, cx, h, s, h, s
    """
    if start + 12 >= len(instructions):
        return None
    ops = instructions[start:start + 13]
    names = [op.operation.name for op in ops]
    if names != ["sdg", "h", "sdg", "h", "cx", "cx", "rz", "cx", "cx", "h", "s", "h", "s"]:
        return None

    q_left  = _qubit_idx(ops[0].qubits[0], qc)
    q_right = _qubit_idx(ops[2].qubits[0], qc)
    cx1_c   = _qubit_idx(ops[4].qubits[0], qc)
    cx1_t   = _qubit_idx(ops[4].qubits[1], qc)
    rz_q    = _qubit_idx(ops[6].qubits[0], qc)

    if cx1_c != q_left or rz_q != q_right:
        return None

    q_jw  = cx1_t
    theta = float(ops[6].operation.params[0]) / 2.0   # keep sign!
    return dict(pauli="YZY", qubits=(q_left, q_jw, q_right),
                theta=theta, end_idx=start + 12)


# ── Synthesis pass ────────────────────────────────────────────────────────────

class GivensHoppingBlock:
    """Represents a detected XZX+YZY hopping pair."""
    __slots__ = ("qubits", "theta", "start_idx", "end_idx")

    def __init__(self, qubits, theta, start_idx, end_idx):
        self.qubits = qubits
        self.theta = theta
        self.start_idx = start_idx
        self.end_idx = end_idx


class GivensRotationSynthesis:
    """
    Detects adjacent exp(-iθ XZX) · exp(-iθ YZY) pairs in a Fermi-Hubbard
    Trotter circuit and replaces each with a 6-CX Givens rotation circuit.

    Each replacement saves 2 abstract CX gates (8 → 6 per hopping term).

    Usage
    -----
    >>> synth = GivensRotationSynthesis()
    >>> result = synth.apply(circuit)
    >>> print(result["cx_saved"])          # abstract CX saved
    >>> print(result["blocks_replaced"])   # number of pairs replaced
    """

    def __init__(self, angle_tol: float = 1e-6, verbose: bool = False) -> None:
        self.angle_tol = angle_tol
        self.verbose = verbose
        self.blocks_replaced: int = 0
        self.cx_saved: int = 0

    def detect_hopping_pairs(self, qc: QuantumCircuit) -> List[GivensHoppingBlock]:
        instructions = list(qc.data)
        blocks: List[GivensHoppingBlock] = []
        i = 0
        while i < len(instructions):
            xzx = _match_xzx(instructions, i, qc)
            if xzx:
                yzy_start = xzx["end_idx"] + 1
                yzy = _match_yzy(instructions, yzy_start, qc)
                if (yzy
                        and yzy["qubits"] == xzx["qubits"]
                        and abs(yzy["theta"] - xzx["theta"]) < self.angle_tol):
                    blocks.append(GivensHoppingBlock(
                        qubits=xzx["qubits"],
                        theta=xzx["theta"],
                        start_idx=i,
                        end_idx=yzy["end_idx"],
                    ))
                    i = yzy["end_idx"] + 1
                    continue
            i += 1
        return blocks

    def apply(self, qc: QuantumCircuit) -> dict:
        """
        Apply synthesis to `qc`.  Returns a dict with:
            circuit, before_cx, after_cx, cx_saved, blocks_replaced
        """
        instructions = list(qc.data)
        before_cx = sum(1 for inst in instructions if inst.operation.name == "cx")

        blocks = self.detect_hopping_pairs(qc)
        if self.verbose:
            print(f"  GivensRotationSynthesis: {len(blocks)} XZX+YZY pairs detected.")

        if not blocks:
            return dict(circuit=qc, before_cx=before_cx, after_cx=before_cx,
                        cx_saved=0, blocks_replaced=0)

        replaced: set[int] = set()
        for blk in blocks:
            replaced.update(range(blk.start_idx, blk.end_idx + 1))
        block_by_start = {blk.start_idx: blk for blk in blocks}

        new_qc = QuantumCircuit(qc.num_qubits,
                                qc.num_clbits if qc.num_clbits else 0)
        i = 0
        while i < len(instructions):
            if i in block_by_start:
                blk = block_by_start[i]
                q_left, q_jw, q_right = blk.qubits
                givens_qc = givens_hopping_circuit(
                    blk.theta, q_left, q_jw, q_right, qc.num_qubits
                )
                new_qc.compose(givens_qc, inplace=True)
                i = blk.end_idx + 1
            elif i in replaced:
                i += 1
            else:
                inst = instructions[i]
                new_qc.append(
                    inst.operation,
                    [new_qc.qubits[_qubit_idx(q, qc)] for q in inst.qubits],
                )
                i += 1

        after_cx = sum(1 for inst in new_qc.data if inst.operation.name == "cx")
        cx_saved = before_cx - after_cx
        self.blocks_replaced = len(blocks)
        self.cx_saved = cx_saved

        if self.verbose:
            print(f"  {before_cx} → {after_cx} CX (saved {cx_saved})")

        return dict(circuit=new_qc, before_cx=before_cx, after_cx=after_cx,
                    cx_saved=cx_saved, blocks_replaced=len(blocks))

    def verify_unitary(
        self,
        original: QuantumCircuit,
        optimised: QuantumCircuit,
        tol: float = 1e-5,
    ) -> bool:
        try:
            U = Operator(original).data
            V = Operator(optimised).data
            return bool(_frobenius_dist(U, V) < tol * np.sqrt(U.shape[0]))
        except MemoryError:
            warnings.warn("Unitary verification skipped: circuit too large.")
            return True


# ── compile_givens convenience function ──────────────────────────────────────

def compile_givens(
    circuit: QuantumCircuit,
    circuit_type: str = "fermi_hubbard",
    dt: float = 0.1,
    order: int = 1,
    verify: bool = True,
) -> dict:
    """
    High-level entry point for the Givens synthesis pass.

    Returns a stats dict with keys:
        before_gates, after_gates, gate_reduction_pct,
        before_depth, after_depth, depth_reduction_pct,
        blocks_replaced, cx_saved, cx_before, cx_after,
        method_used, verified, error
    """
    before_gates = sum(circuit.count_ops().values())
    before_depth = circuit.depth()
    before_cx = sum(1 for inst in circuit.data if inst.operation.name == "cx")

    synth = GivensRotationSynthesis(verbose=False)
    try:
        result = synth.apply(circuit)
    except Exception as exc:
        return dict(
            before_gates=before_gates, after_gates=before_gates,
            gate_reduction_pct=0.0, before_depth=before_depth,
            after_depth=before_depth, depth_reduction_pct=0.0,
            blocks_replaced=0, cx_saved=0,
            cx_before=before_cx, cx_after=before_cx,
            method_used="givens_synthesis_failed",
            verified=False, error=str(exc),
        )

    opt = result["circuit"]
    after_gates = sum(opt.count_ops().values())
    after_depth = opt.depth()
    after_cx = result["after_cx"]

    verified = False
    if verify and circuit.num_qubits <= 8:
        verified = synth.verify_unitary(circuit, opt)

    gate_red = (before_gates - after_gates) / max(before_gates, 1) * 100
    depth_red = (before_depth - after_depth) / max(before_depth, 1) * 100

    return dict(
        before_gates=before_gates,
        after_gates=after_gates,
        gate_reduction_pct=round(gate_red, 2),
        before_depth=before_depth,
        after_depth=after_depth,
        depth_reduction_pct=round(depth_red, 2),
        blocks_replaced=result["blocks_replaced"],
        cx_saved=result["cx_saved"],
        cx_before=before_cx,
        cx_after=after_cx,
        method_used="givens_6cx",
        verified=verified,
        error=None,
    )
