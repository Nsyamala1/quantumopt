"""
quantumopt/passes/givens_synthesis.py

Givens rotation synthesis for 1D Fermi-Hubbard Trotter circuits.

Key result (numerically verified):
    exp(-iθ(XZX + YZY)) requires exactly 6 CX gates on a linear qubit
    chain, compared with the naive 8 CX from two separate Pauli
    exponentials.  This yields a 25% reduction in abstract CX count per
    hopping pair.

Mathematical basis:
    XZX + YZY = (XX+YY)_{q0,q2} ⊗ Z_{q1}
    Pairs {|001⟩,|100⟩} and {|011⟩,|110⟩} each undergo an Rx rotation
    with opposite signs determined by Z_{q1}.

Numerical result:
    4 CX is INSUFFICIENT (min Frobenius dist ~0.07 for all templates tested).
    6 CX with template [(0,1),(1,2),(0,1),(1,2),(0,1),(1,2)] is EXACT.
    Parameters found by L-BFGS-B with 200 random restarts (63 free variables).
    Cached per angle so optimisation runs only once per unique θ.
"""

